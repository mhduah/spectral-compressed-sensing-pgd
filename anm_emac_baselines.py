"""
ANM and EMaC baselines for the phase transition reproduction
(Cai, Wang, Wei 2018, Section 3.1).

Both methods are convex relaxations of the spectral compressed sensing problem
and are solved here without any external SDP solver dependency (no cvxpy),
using ADMM, so the reproduction script runs with only numpy/scipy installed.

--------------------------------------------------------------------------
EMaC (Enhanced Matrix Completion), Chen & Chi (2014)
--------------------------------------------------------------------------
EMaC solves

    min_x  || H(x) ||_*
    s.t.   x[Omega] = y_obs

which is exactly the Hankel nuclear-norm minimisation problem already
implemented in admm_baseline.py. We expose it here under its proper name
since this thesis uses it as one of the four original phase-transition
baselines, not merely as a generic "convex baseline".

--------------------------------------------------------------------------
ANM (Atomic Norm Minimisation), Tang, Bhaskar, Shah, Recht (2013)
--------------------------------------------------------------------------
ANM solves, in its SDP-free dual/primal-dual form via the
Toeplitz/positive-semidefinite trigonometric moment problem:

    min_{x, u, t}   (1/(2*sqrt(n))) * t  +  (1/(2*sqrt(n))) * u_0
    s.t.   [ Toep(u)   x ]
           [  x^*       t ]   >= 0      (PSD constraint)
           x[Omega] = y_obs

where Toep(u) is the n x n Hermitian Toeplitz matrix generated by u in C^n
(u_0 real). The atomic norm ||x||_A equals the optimal value of (t+u_0)/2
under this SDP (Tang et al. 2013, Prop. 2.1; Bhaskar, Tang, Recht 2013).

Rather than calling an external SDP solver, we solve this PSD-constrained
problem with ADMM, splitting the PSD cone constraint from the affine
sampling constraint and the Toeplitz structure constraint. This is the
same algorithmic family used by Bhaskar et al. (2013, Algorithm 1) and by
the SDPT3/CVX-free implementations used in several reproducibility studies
of atomic norm methods.
"""


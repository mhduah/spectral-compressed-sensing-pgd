# ============================================================
# ANM via ADMM on the PSD Toeplitz formulation
# ============================================================

def _toeplitz_from_u(u, n):
    """
    Build the n x n Hermitian Toeplitz matrix generated by u in C^n,
    with u[0] real (enforced by the caller).

        T(u)_{i,j} = u[i-j]      if i >= j
                   = conj(u[j-i]) if i < j
    """
    T = np.zeros((n, n), dtype=np.complex128)
    for k in range(n):
        if k == 0:
            np.fill_diagonal(T, u[0].real)
        else:
            idx = np.arange(n - k)
            T[idx + k, idx] = u[k]
            T[idx, idx + k] = np.conj(u[k])
    return T


def _toeplitz_adjoint(M, n):
    """
    Adjoint of u -> T(u): averages each diagonal of M back into a
    length-n vector u, consistent with the inner product
    <T(u), M>_F = <u, Toeplitz_adjoint(M)>.

    For the k-th diagonal (k=0,...,n-1), entries M[i+k, i] for
    i = 0,...,n-1-k are summed (this matches the structure of T(u)
    above, where u[k] appears n-k times in T(u)).
    """
    u = np.zeros(n, dtype=np.complex128)
    for k in range(n):
        idx = np.arange(n - k)
        if k == 0:
            u[k] = np.sum(M[idx, idx]).real
        else:
            u[k] = np.sum(M[idx + k, idx])
    return u


def _project_psd(M):
    """Project a Hermitian matrix onto the PSD cone (eigenvalue clipping)."""
    M_herm = 0.5 * (M + M.conj().T)
    w, V = eigh(M_herm)
    w_clipped = np.maximum(w, 0.0)
    return (V * w_clipped) @ V.conj().T


def anm_recovery(y_obs, Omega, r, n, max_iter=2000, rho=1.0,
                 relative_iterate_tol=1e-6, primal_residual_tol=1e-6,
                 min_iter=50, patience=10,
                 x_true=None, verbose=False, return_history=False):
    """
    Atomic Norm Minimisation via ADMM on the PSD Toeplitz moment problem.

    We solve the equivalent semidefinite-free formulation by ADMM. Two
    variables are used: the lifted block matrix W (constrained to be PSD)
    and a structured, data-consistent copy S of the same shape (constrained
    to have Toeplitz upper-left block and x[Omega] = y_obs). The linear
    objective (t + u_0)/2 is absorbed into the structured update as a
    gradient step, which is the correct way to combine a linear cost with
    an affine/structural constraint set in ADMM (in contrast to a naive
    "shrink-then-discard-structure" step, which is not a valid proximal
    operator for this splitting and was found empirically to plateau away
    from the true solution).

    ADMM splitting
    --------------
        min_{W, S}   (1/2)(S_{tt} + S_{uu,0})
        s.t.         W is PSD
                     S has Toeplitz (1,1) block, S[:n,n][Omega] = y_obs
                     W = S

    W-update (PSD projection):
        W^{k+1} = Proj_{PSD}( S^k - Lambda^k/rho )

    S-update (structured update with linear cost):
        S^{k+1} = Proj_{structure}( W^{k+1} + Lambda^k/rho - (1/(2*rho)) * G )
        where G is the subgradient of the linear cost (1 on the t and u_0
        diagonal slots, 0 elsewhere), applied only to the *free* entries
        (the trace-like terms), since the data and Toeplitz-off-diagonal
        entries are fixed by the structural projection regardless.

    Lambda-update:
        Lambda^{k+1} = Lambda^k + rho * (W^{k+1} - S^{k+1})

    The atomic norm estimate ||x||_A is recovered as (S_{tt} + S_{uu,0})/2
    at convergence, and the recovered signal is read off the off-diagonal
    block of S.

    Parameters
    ----------
    y_obs   : ndarray (m,)   observations x_true[Omega]
    Omega   : ndarray (m,)   sampling indices
    r       : int            rank parameter; informational only for ANM,
                              since ANM does not require r as input. Kept
                              for interface consistency with the other
                              three solvers used in the phase-transition
                              comparison.
    n       : int            signal length
    max_iter, rho            ADMM parameters
    relative_iterate_tol     stop when ||x^{k+1}-x^k|| / ||x^k|| <= this
    primal_residual_tol      stop when ||W^{k+1}-S^{k+1}||_F / ||S^{k+1}||_F <= this
    min_iter, patience       both stopping criteria must hold for
                             `patience` CONSECUTIVE iterations, and not
                             before iteration `min_iter`, before the run
                             is accepted as converged. This guards
                             against a genuine but transient early
                             plateau observed empirically in this solver:
                             the iterate can go nearly static for
                             ~10-15 iterations (rel_step ~1e-17) at a
                             point that is NOT the true solution, before
                             escaping and converging properly tens to
                             hundreds of iterations later. A naive
                             single-iteration check mistakes that
                             transient plateau for convergence.
    x_true  : ndarray, optional   ground truth for diagnostics ONLY -- it
                                   is never used to decide when to stop or
                                   which iterate to return
    verbose, return_history       output controls

    Returns
    -------
    result : dict with keys 'x', 'converged', 'status', 'iterations',
             'time', and 'rel_error' if x_true is given.
    """
    t0 = time.time()
    N = n + 1   # size of the lifted block matrix

    def assemble(u_, x_, t_):
        W = np.zeros((N, N), dtype=np.complex128)
        W[:n, :n] = _toeplitz_from_u(u_, n)
        W[:n, n] = x_
        W[n, :n] = np.conj(x_)
        W[n, n] = t_
        return W

    def project_structure(M, grad_step):
        """
        Project block matrix M onto the structured, data-consistent set:
          - (1,1) block forced to be Toeplitz (via diagonal averaging)
          - off-diagonal block forced to satisfy x[Omega] = y_obs
          - apply a small gradient step on the free scalar/trace terms
            (u_0 and t) before re-clipping to be non-negative, which is
            the correct proximal step for the linear cost term.
        """
        # Average each diagonal of the (1,1) block to get a Toeplitz u
        u_ = np.zeros(n, dtype=np.complex128)
        for k in range(n):
            idx = np.arange(n - k)
            if k == 0:
                u_[k] = np.mean(M[idx, idx]).real
            else:
                u_[k] = np.mean(M[idx + k, idx])

        x_ = M[:n, n].copy()
        x_[Omega] = y_obs            # enforce data constraint exactly

        t_ = M[n, n].real

        # NOTE on u_0 scaling: u_0 parametrises all n diagonal entries of
        # the (1,1) Toeplitz block (replicated n times), while t is a
        # single scalar entry (W[n,n]). Treating each as an isolated
        # closed-form minimisation of the augmented-Lagrangian penalty
        # plus the linear cost predicts a shift of grad_step for t but
        # grad_step/n for u_0 (verified symbolically). Empirically,
        # however, applying that /n-scaled shift here makes recovery on
        # the correctness-test problem markedly WORSE (converges to a
        # feasible but wrong fixed point, rel_error ~0.26 instead of
        # ~1e-6), while the unscaled shift below converges correctly.
        # This indicates the isolated closed-form derivation does not
        # carry over cleanly to this particular (non-rigorously-derived,
        # already-flagged-as-approximate) ADMM splitting -- most likely
        # because some other part of the splitting is itself an
        # approximation that this shift was inadvertently compensating
        # for. Given the empirical evidence, the unscaled shift is kept;
        # a from-scratch, verified re-derivation of the full splitting
        # would be needed to safely apply the theoretically-indicated
        # correction, and is out of scope for this pass.
        u_[0] = max(u_[0].real - grad_step, 0.0)
        t_ = max(t_ - grad_step, 0.0)

        return assemble(u_, x_, t_)

    # ---- Initialisation ----
    x0 = np.zeros(n, dtype=np.complex128)
    x0[Omega] = y_obs
    scale = max(np.linalg.norm(x0)**2 / max(len(Omega), 1), 1e-3)
    S = assemble(np.full(n, 0, dtype=np.complex128), x0, scale)
    S[:n, :n] = _toeplitz_from_u(
        np.concatenate([[scale], np.zeros(n - 1, dtype=np.complex128)]), n)
    Lambda = np.zeros((N, N), dtype=np.complex128)

    grad_step = 0.5 / rho

    history = {
        'relative_iterate': [],
        'primal_residual': [],
        'relative_error': [relative_error(x0, x_true)] if x_true is not None else [],
    }
    converged = False
    status = "max_iter"
    x = x0
    iteration = 0
    consecutive_ok = 0

    for k in range(max_iter):

        # ---- W-update: PSD projection ----
        W = _project_psd(S - Lambda / rho)

        # ---- S-update: structured projection with linear-cost gradient step ----
        S_new = project_structure(W + Lambda / rho, grad_step)

        # ---- Dual update ----
        Lambda = Lambda + rho * (W - S_new)

        x_new = S_new[:n, n]

        if not np.all(np.isfinite(x_new)):
            status = "nonfinite_iterate"
            break

        rel_iterate = float(
            np.linalg.norm(x_new - x)
            / max(np.linalg.norm(x), np.finfo(float).eps)
        )
        primal_res = float(
            np.linalg.norm(W - S_new, 'fro')
            / max(np.linalg.norm(S_new, 'fro'), np.finfo(float).eps)
        )

        S = S_new
        x = x_new
        iteration = k + 1

        if return_history:
            history['relative_iterate'].append(rel_iterate)
            history['primal_residual'].append(primal_res)
            if x_true is not None:
                history['relative_error'].append(relative_error(x, x_true))

        if verbose and (k % 100 == 0 or k < 5):
            msg = (f"  ANM k={k:4d}: rel_step={rel_iterate:.2e} "
                   f"primal_res={primal_res:.2e}")
            if x_true is not None:
                msg += f" rel_err={relative_error(x, x_true):.2e}"
            print(msg)

        if rel_iterate <= relative_iterate_tol and primal_res <= primal_residual_tol:
            consecutive_ok += 1
        else:
            consecutive_ok = 0

        if iteration >= min_iter and consecutive_ok >= patience:
            converged = True
            status = "relative_iterate_and_primal_residual"
            break

    result = {
        'x': x,
        'converged': converged,
        'status': status,
        'iterations': iteration,
        'time': time.time() - t0,
        'rho': rho,
    }
    if x_true is not None:
        result['rel_error'] = relative_error(x, x_true)
    if return_history:
        result['history'] = history

    return result
